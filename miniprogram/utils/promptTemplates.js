// 获取指定模式的提示词
function getPrompt(mainMode, subMode) {
  try {
    const modeGroup = PROMPTS[mainMode];
    if (!modeGroup) return PROMPTS.general;
    const prompt = modeGroup[subMode];
    return prompt || PROMPTS.general;
  } catch (e) {
    return PROMPTS.general;
  }
}

